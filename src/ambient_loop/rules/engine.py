"""Rules and insights engine (brief §3).

Each rule checks a scenario and returns findings. Every finding carries:
  - severity: info, warn or fail
  - a plain-English message
  - the numbers behind it
  - the evidence the rule rests on
Rules marked "(Milieu toolkit addition)" are additions to the brief, each with its reference.
Every rule has synthetic tests in which it must fire and must not fire (tests/unit/test_rules.py).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from ambient_loop.physics.fluids import get_fluid, htc_factor, pressure_drop_factor
from ambient_loop.physics.pumps import max_dT_from_min_flow


@dataclass(frozen=True)
class Finding:
    rule: str
    title: str
    severity: str  # info | warn | fail
    message: str
    evidence: str
    numbers: dict[str, float] = field(default_factory=dict)


@dataclass
class Context:
    """What the rules need: arrangement, case result, loads and optional recovery summary."""

    case: Any  # reporting.full_summary.CaseResult
    project: Any
    demand_kW: dict[str, np.ndarray]
    dry_bulb_C: np.ndarray
    recovery: Any | None = None  # recovery.report.RecoverySummary
    dhw_peak_fraction: float | None = None
    healthcare: bool = False

    @property
    def arr(self) -> Any:
        return self.case.arrangement

    def o(self, k: str) -> np.ndarray:
        return self.case.result.ledger.derived[f"o:{k}"]


Rule = Callable[[Context], list[Finding]]
RULES: list[tuple[str, str, str, Rule]] = []


def rule(rid: str, title: str, evidence: str) -> Callable[[Rule], Rule]:
    def deco(f: Rule) -> Rule:
        RULES.append((rid, title, evidence, f))
        return f
    return deco


def F(rid: str, sev: str, msg: str, **nums: float) -> Finding:
    title, ev = next((t, e) for r, t, e, _ in RULES if r == rid)
    return Finding(rid, title, sev, msg, ev, {k: float(v) for k, v in nums.items()})


def run_rules(ctx: Context) -> list[Finding]:
    out: list[Finding] = []
    for _rid, _t, _e, f in RULES:
        out.extend(f(ctx))
    order = {"fail": 0, "warn": 1, "info": 2}
    return sorted(out, key=lambda x: order[x.severity])


MWh = 1e3


@rule("R1", "Double lifts lose",
      "Brief rule 1. Each lift adds its own approach losses and compressor inefficiency: "
      "COP_series = 1 / (1/COP2 + (1 − 1/COP2)/COP1) is below a single lift across the same span "
      "(Carnot argument; Kemp 2007 §6.3).")
def r1(ctx: Context) -> list[Finding]:
    out = []
    a = ctx.arr
    if a.dhw and a.dhw.generator.type == "cascade":
        w = ctx.o("W_gen").sum() + ctx.o("W_s1").sum()
        g = ctx.o("G").sum()
        out.append(F("R1", "warn", f"DHW is lifted twice (loop → {a.dhw.generator.intermediate_C:g} °C → {a.dhw.store_C:g} °C) "
                     f"with generated intermediate heat: series COP {g / w:.2f}.", series_cop=g / w))
    ext = ctx.case.result.ledger.derived.get("loop:extraction")
    ashp = ctx.o("ashp_d").sum()
    if ext is not None and ext.sum() > 0 and ashp / ext.sum() > 0.5:
        out.append(F("R1", "warn", f"{ashp / ext.sum():.0%} of the heat that heat pumps take from the loop is first "
                     "generated by the rooftop ASHPs, so the loop works as a two-stage cascade (air → loop → service). "
                     "A single-lift air-source or CO₂ generator for the largest heat service is worth testing.",
                     generated_share=ashp / ext.sum()))
    return out


@rule("R2", "Use recovered heat directly where its temperature allows",
      "Brief rule 2. A heat exchanger needs no compressor; using 45 °C waste heat on the 10 °C cold feed "
      "beats feeding it to an evaporator.")
def r2(ctx: Context) -> list[Finding]:
    a = ctx.arr
    rej = ctx.o("cond_rej").sum()
    if a.dhw and not a.dhw.preheat and a.cooling and rej > 0.05 * ctx.o("G").sum():
        return [F("R2", "warn", f"{rej / MWh:,.0f} MWh/yr of cooling heat goes to the loop while DHW is heated from "
                  "cold. Heat recovery to a cold-feed preheat (archetype 3) would use it without a compressor.",
                  rejected_MWh=rej / MWh)]
    if a.dhw and a.dhw.preheat:
        return [F("R2", "info", f"Preheat delivers {ctx.o('hr_P').sum() / MWh:,.0f} MWh/yr to the cold feed by heat exchange.",
                  preheat_MWh=ctx.o("hr_P").sum() / MWh)]
    return []


@rule("R3", "Evaporator temperature is set by the leaving fluid",
      "Brief rule 3. COP follows the evaporator leaving temperature; a wide source ΔT mainly lowers it. "
      "Large temperature falls belong on cold-water preheat.")
def r3(ctx: Context) -> list[Finding]:
    a = ctx.arr
    if a.dhw and a.dhw.generator.source.startswith("hr") and a.hr:
        dT = a.hr.flow_C - a.hr.return_C
        if dT > 10:
            return [F("R3", "warn", f"The DHW heat pump evaporator works across {dT:g} K on the heat-recovery circuit; "
                      f"its COP is set by the {a.hr.return_C:g} °C leaving temperature. The fall would be better used "
                      "on preheat.", dT=dT)]
    return []


@rule("R4", "Condenser COP is set by leaving temperature; minimum flow caps ΔT",
      "Brief rule 4. ΔT_max = Q / (ρ c_p V̇_min) at full capacity; a wider design ΔT breaks the machine's "
      "minimum flow (manufacturer limit).")
def r4(ctx: Context) -> list[Finding]:
    out = []
    a = ctx.arr
    w = get_fluid("water")
    if a.cooling and a.cooling.min_flow_m3s and a.buffer and a.hr:
        dT = a.hr.flow_C - a.buffer.t_return_C
        mx = max_dT_from_min_flow(a.cooling.unit_kW, a.cooling.min_flow_m3s, w.rho(30), w.cp(30))
        sev = "fail" if dT > mx else "info"
        out.append(F("R4", sev, f"Charging the buffer {a.hr.flow_C:g} → {a.buffer.t_return_C:g} °C needs ΔT {dT:g} K; "
                     f"minimum condenser flow allows up to {mx:.1f} K at full capacity.", design_dT=dT, max_dT=mx))
    return out


@rule("R4b", "CO₂: COP is set by gas-cooler ENTERING water temperature",
      "Milieu toolkit addition. Transcritical CO₂ loses COP steeply as return water warms (Nekså 2002, "
      "Int. J. Refrig. 25:421; manufacturer data show reduction above ~29 °C inlet).")
def r4b(ctx: Context) -> list[Finding]:
    a = ctx.arr
    out = []
    if a.dhw and a.dhw.generator.type == "co2":
        if a.dhw.reheat is None and a.dhw.circulation_fraction > 0:
            out.append(F("R4b", "warn", f"CO₂ also reheats circulation return at {a.dhw.circulation_return_C:g} °C: "
                         "a separate reheat (archetype 7) avoids running CO₂ at high inlet temperature."))
        if a.dhw.preheat:
            out.append(F("R4b", "warn", "Preheating the cold feed raises the CO₂ inlet temperature and lowers its COP; "
                         "check that the preheat gain outweighs the CO₂ loss."))
    return out


@rule("R5", "Heat recovery only pays when demands overlap",
      "Brief rule 5. Value depends on hourly coincidence of rejected and demanded heat plus storage shift.")
def r5(ctx: Context) -> list[Finding]:
    if ctx.recovery is None:
        return []
    cf = ctx.recovery.coincidence
    if not np.isfinite(cf):
        return []
    sev = "warn" if cf < 0.6 else "info"
    best = max(ctx.recovery.storage_MWh.values()) if ctx.recovery.storage_MWh else 0.0
    return [F("R5", sev, f"Coincidence factor {cf:.2f}. Storage in the tested range adds up to {best:,.0f} MWh/yr of "
              "recovered source heat.", coincidence=cf, storage_MWh=best)]


@rule("R6", "A flat DHW profile flatters heat recovery",
      "Brief rule 6. A peak hour below ~6 % of daily energy is effectively flat; CIBSE Guide G (2014) hotel "
      "profiles peak at roughly 10–15 %. Plant duty is not the peak-hour draw-off.")
def r6(ctx: Context) -> list[Finding]:
    f = ctx.dhw_peak_fraction
    if f is None or not np.isfinite(f):
        return []
    if f < 0.06:
        return [F("R6", "warn", f"DHW peak hour is {f:.1%} of the daily total. Re-run with a shaped profile "
                  "(occupancy × litres/bed/day × CIBSE/CIPHE hourly shape) before relying on recovery figures.",
                  peak_fraction=f)]
    return []


@rule("R7", "Storage is what lets recovered heat be used",
      "Brief rule 7. Stratified primary stores at wide ΔT hold several times more energy: E = V ρ c_p ΔT.")
def r7(ctx: Context) -> list[Finding]:
    a = ctx.arr
    if a.buffer and a.hr:
        dT = a.hr.flow_C - a.buffer.t_return_C
        e = a.buffer.volume_m3 * 4.18 * dT / 3.6
        sev = "warn" if dT < 10 else "info"
        return [F("R7", sev, f"Buffer {a.buffer.volume_m3:g} m³ across {dT:g} K holds about {e:,.0f} kWh "
                  f"(≈{a.buffer.volume_m3 * 4.18 * 5 / 3.6:,.0f} kWh at 5 K). Charged {ctx.o('buf_ch').sum() / MWh:,.0f} MWh/yr.",
                  capacity_kWh=e, dT=dT)]
    return []


@rule("R8", "Legionella control (HSG274 Part 2)",
      "HSE HSG274 Part 2 (2014): store hot water at ≥ 60 °C, distribute so outlets reach ≥ 50 °C (≥ 55 °C in "
      "healthcare) within one minute; avoid potable storage at 20–45 °C; return must not pass through preheat.")
def r8(ctx: Context) -> list[Finding]:
    a = ctx.arr
    out = []
    if not a.dhw:
        return out
    if a.dhw.store_C < 60:
        out.append(F("R8", "fail", f"DHW stored at {a.dhw.store_C:g} °C, below 60 °C.", store_C=a.dhw.store_C))
    lim = 55 if ctx.healthcare else 50
    if a.dhw.circulation_return_C < lim:
        out.append(F("R8", "fail", f"Circulation return {a.dhw.circulation_return_C:g} °C is below {lim} °C."))
    if a.dhw.preheat and a.dhw.preheat.stores_potable:
        out.append(F("R8", "fail", "Preheat stores potable water at 20–50 °C: use an instantaneous plate HX on the "
                     "cold feed, or a pasteurisation regime."))
    if a.buffer and a.buffer.potable:
        out.append(F("R8", "fail", "The heat-recovery buffer holds potable water; keep stores on the primary side."))
    if a.dhw.preheat and not a.dhw.preheat.stores_potable:
        out.append(F("R8", "info", "Preheat is an instantaneous PHX on the cold feed with no warm potable storage; "
                     "the secondary return must bypass it."))
    return out


@rule("R9", "Dry coolers only work below the loop temperature",
      "Brief rule 9. Available only when T_db < T_fluid,in − approach (5–8 K); do not screen by the rating "
      "condition. On a heat-short loop a dry cooler may be almost worthless.")
def r9(ctx: Context) -> list[Finding]:
    a = ctx.arr
    dcs = [b for b in a.surplus if b.type == "dry_cooler"]
    if not dcs:
        return []
    lf = ctx.case.result.ledger.derived["T_loop_flow"]
    b = dcs[0]
    phys = int((ctx.dry_bulb_C < lf - b.approach_min_K).sum())
    screen = int((ctx.dry_bulb_C <= 27.0).sum())
    rej = ctx.o("dc_r").sum()
    deficit = ctx.o("ashp_d").sum() + ctx.o("loop_backup").sum()
    out = [F("R9", "info", f"Dry cooler available {phys:,} h/yr at the loop's own temperature (vs {screen:,} h by a "
             f"27 °C screening cutoff); it rejected {rej / MWh:,.0f} MWh/yr.", hours_available=phys,
             hours_screening=screen, rejected_MWh=rej / MWh)]
    if deficit > 5 * max(rej, 1.0):
        out.append(F("R9", "warn", f"The loop is short of heat ({deficit / MWh:,.0f} MWh/yr generated vs "
                     f"{rej / MWh:,.0f} MWh/yr rejected): the dry cooler earns little. Rejected heat is worth more stored "
                     "or reused.", deficit_MWh=deficit / MWh))
    return out


@rule("R10", "Part load and sequencing matter; flag oversizing",
      "Brief rule 10. Plant-to-peak ratio above ~1.5 means long low-load running; HT screws lose COP at part load "
      "(constant condenser flow), inverter scrolls gain. EN 14825 cycling below minimum capacity.")
def r10(ctx: Context) -> list[Finding]:
    out = []
    a = ctx.arr
    plr = ctx.case.result.plr
    peaks = ctx.case.result.peaks_kW
    checks = []
    if a.dhw:
        checks.append(("dhw_gen", a.dhw.generator.count * a.dhw.generator.unit_kW, peaks.get("DHW", 0.0)))
    if a.cooling:
        checks.append(("cooling", a.cooling.count * a.cooling.unit_kW * 0.78, peaks.get("CHW", 0.0)))
    for name, inst, peak in checks:
        if peak > 0:
            r = inst / peak
            med = float(np.median(plr[name])) if plr.get(name) else float("nan")
            sev = "warn" if r > 1.5 or (np.isfinite(med) and med < 0.35) else "info"
            out.append(F("R10", sev, f"{name}: installed {inst:,.0f} kW vs peak {peak:,.0f} kW (ratio {r:.2f}); "
                         f"median lead-unit PLR {med:.2f}, sequencing {(a.dhw.generator if name == 'dhw_gen' else a.cooling).sequencing}.",
                         plant_to_peak=r, median_plr=med))
    return out


@rule("R11", "Pumps often decide the real result",
      "Brief rule 11. Affinity laws, minimum speed and circuit ΔT; a 20–30 kW average pump load can cut a "
      "scheme's seasonal ratio by 20–25 %. Efficiencies always state whether pumps are included.")
def r11(ctx: Context) -> list[Finding]:
    p = ctx.case.pumps_MWh
    e = ctx.case.electricity_MWh
    if not ctx.arr.pumps_included:
        return [F("R11", "warn", "Pumps are excluded from this result; real seasonal ratios will be lower.")]
    share = p / e if e else 0.0
    sev = "warn" if share > 0.08 else "info"
    return [F("R11", sev, f"Pumps use {p:,.0f} MWh/yr ({share:.1%} of total, {p * 1e3 / 8760:,.1f} kW average).",
              pumps_MWh=p, share=share)]


@rule("R12", "Fluids and freeze protection",
      "Brief rule 12. Glycol raises pumping energy and lowers HX performance; circuits with different fluids or "
      "pressurisation units must be separated by a heat exchanger; trace heating does not protect a unit's own HX "
      "during a power cut. Properties: Melinder (2010) via CoolProp.")
def r12(ctx: Context) -> list[Finding]:
    a = ctx.arr
    out = []
    if a.loop and a.loop.fluid != "water":
        f, w = get_fluid(a.loop.fluid), get_fluid("water")
        pdf = pressure_drop_factor(f, w, 15.0)
        hf = htc_factor(f, w, 15.0)
        out.append(F("R12", "info", f"Loop on {f.label}: hydraulic power ×{pdf:.2f} vs water at the same duty and ΔT; "
                     f"convective HTC ×{hf:.2f}. Building circuits on water need an isolating HX and a separate "
                     "pressurisation unit.", pump_factor=pdf, htc_factor=hf))
    has_air = any(b.type in ("ashp", "dry_cooler") for b in a.deficit + a.surplus)
    if has_air and a.loop and a.loop.fluid == "water":
        out.append(F("R12", "warn", "Roof plant on a water loop: compare (a) glycol throughout, (b) water in the building "
                     "with a roof-level glycol HX, (c) water with freeze protection. Trace heating does not protect "
                     "the unit's own heat exchanger during a power cut."))
    return out


@rule("R13", "Allocation conventions change per-service ratios, not the total",
      "Brief rule 13. Report the system ratio with per-service figures under pro-rata and incremental conventions.")
def r13(ctx: Context) -> list[Finding]:
    c = ctx.case
    parts = []
    for conv in ("pro_rata", "incremental"):
        parts.append(conv + ": " + ", ".join(f"{s} {m.value:.2f}" for s, m in sorted(c.per_service[conv].items())))
    return [F("R13", "info", f"System {c.system.value:.2f}. " + "; ".join(parts) + ".", system=c.system.value)]


@rule("R14", "Targets have a headroom budget",
      "Brief rule 14. Allowed electricity = Q / target; subtract the machine's own electricity to get the "
      "budget left for rejection, pumps and auxiliaries.")
def r14(ctx: Context) -> list[Finding]:
    out = []
    c = ctx.case
    machine = {"CHW": c.elec_by_component_MWh.get("cooling", 0.0),
               "DHW": c.elec_by_component_MWh.get("dhw_gen", 0.0) + c.elec_by_component_MWh.get("dhw_stage1", 0.0),
               "LTHW": c.elec_by_component_MWh.get("lthw_hp", 0.0)}
    for t in ctx.project.targets:
        if t.service not in c.demand_MWh:
            continue
        allowed = c.demand_MWh[t.service] / t.seasonal_ratio
        head = allowed - machine.get(t.service, 0.0)
        got = c.per_service.get(t.allocation, c.per_service["incremental"]).get(t.service)
        ok = got is not None and got.value >= t.seasonal_ratio
        sev = "info" if ok else ("fail" if head < 0 else "warn")
        out.append(F("R14", sev, f"{t.service} target {t.seasonal_ratio:g} ({t.allocation}): allowed {allowed:,.0f} MWh, "
                     f"machine {machine.get(t.service, 0):,.0f} MWh, headroom {head:,.0f} MWh for rejection/pumps; "
                     f"achieved {got.value if got else float('nan'):.2f}.", headroom_MWh=head))
    return out


@rule("M1", "Performance outside the supplied map",
      "Milieu toolkit addition. Interpolation within a map is fine; extrapolation is flagged (brief §2.3).")
def m1(ctx: Context) -> list[Finding]:
    out = []
    for k, h in ctx.case.envelope_hours.items():
        if h > 0:
            sev = "warn" if h > 438 else "info"
            out.append(F("M1", sev, f"{k}: {h:,} running hours outside the model's map or envelope (values held and "
                         "flagged [Extrapolated]).", hours=h))
    return out


@rule("M2", "Backup and unmet energy",
      "Milieu toolkit addition. Unmet load is shown, never absorbed (design principle); electric backup hours "
      "indicate undersized or mis-sequenced plant.")
def m2(ctx: Context) -> list[Finding]:
    out = []
    for k, h in ctx.case.flags.items():
        if h > 0 and ("backup" in k or "Unmet" in k or "immersion" in k):
            out.append(F("M2", "warn", f"{k}: {h:,} h.", hours=h))
    return out
